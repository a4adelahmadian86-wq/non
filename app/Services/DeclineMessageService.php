        $cursor = $session->get('farast.decline.cursor');
        if (! is_int($cursor)) $cursor = random_int(0, self::MOD - 1);
        $cursor = ($cursor + self::STEP) % self::MOD;
        $session->put('farast.decline.cursor', $cursor);

        $i = $cursor;
        $a = $i % 20; $i = intdiv($i, 20);
        $b = $i % 20; $i = intdiv($i, 20);
